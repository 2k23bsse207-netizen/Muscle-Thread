import assert from 'node:assert/strict'
import { test } from 'node:test'
import { adminToken, catalog, orderFixture, prisma, request, userId, userToken } from './helpers.js'

test('Dashboard: real payment/revenue/orders/sales/customer/inventory statistics, currency/date isolation, bestsellers and empty buckets', async () => {
  await request('/admin/dashboard', { status: 401 })
  await request('/admin/dashboard', { token: userToken, status: 403 })
  const createdAt = new Date('2024-02-10T12:00:00Z')
  const paid = await orderFixture('dashboard-paid', userId, { status: 'DELIVERED', totalCents: 5000, payment: 'PAID', createdAt })
  const refunded = await orderFixture('dashboard-refunded', userId, { status: 'REFUNDED', totalCents: 2000, payment: 'REFUNDED', createdAt })
  await orderFixture('dashboard-pending', userId, { totalCents: 1000, createdAt })
  await orderFixture('dashboard-eur', userId, { status: 'PAID', totalCents: 9000, payment: 'PAID', currency: 'EUR', createdAt })
  await prisma.payment.updateMany({ where: { orderId: paid.order.id }, data: { createdAt, updatedAt: createdAt } })
  await prisma.payment.updateMany({ where: { orderId: refunded.order.id }, data: { createdAt, updatedAt: new Date('2024-02-11T12:00:00Z') } })
  const prev = await orderFixture('dashboard-prev', userId, { status: 'PAID', totalCents: 4000, payment: 'PAID', createdAt: new Date('2024-01-10T12:00:00Z') })
  await prisma.payment.updateMany({ where: { orderId: prev.order.id }, data: { createdAt: new Date('2024-01-10T12:00:00Z'), updatedAt: new Date('2024-01-10T12:00:00Z') } })
  const low = await catalog('dashboard-low', { stock: 1 })
  await prisma.productVariant.update({ where: { id: low.variant.id }, data: { lowStockThreshold: 2 } })
  const path = '/admin/dashboard?from=2024-02-01T00:00:00Z&to=2024-02-29T23:59:59Z&currency=USD&limit=20'
  const { body } = await request(path, { token: adminToken })
  assert.equal(body.orders.total, 3)
  assert.equal(body.orders.paid, 1)
  assert.equal(body.orders.byStatus.DELIVERED, 1)
  assert.equal(body.orders.byStatus.REFUNDED, 1)
  assert.equal(body.orders.byStatus.PENDING, 1)
  assert.equal(body.revenue.grossCents, 7000)
  assert.equal(body.revenue.refundedCents, 2000)
  assert.equal(body.revenue.netCents, 5000)
  assert.equal(body.revenue.averageOrderValueCents, 5000)
  assert.equal(body.sales.unitsSold, 2)
  assert.equal(body.sales.merchandiseSalesCents, 5000)
  assert.equal(body.customers.purchasing, 1)
  assert.equal(body.customers.new, 0)
  assert.equal(body.bestsellers.length, 1)
  assert.equal(body.bestsellers[0].productId, paid.product.id)
  assert.equal(body.bestsellers[0].unitsSold, 2)
  assert.equal(body.bestsellers[0].merchandiseSalesCents, 5000)
  assert.equal(body.salesSeries.length, 29)
  assert.equal(body.salesSeries[0].orders, 0)
  const tenth = body.salesSeries.find((row: { date: string }) => row.date === '2024-02-10')
  const eleventh = body.salesSeries.find((row: { date: string }) => row.date === '2024-02-11')
  assert.equal(tenth.grossRevenueCents, 7000)
  assert.equal(tenth.orders, 3)
  assert.equal(eleventh.refundedCents, 2000)
  assert.equal(eleventh.revenueCents, -2000)
  assert.equal(body.inventory.lowStock >= 1, true)
  assert.equal(body.lowStock.some((row: { id: string }) => row.id === low.variant.id), true)
  assert.equal(body.previous.grossCents, 4000)
  assert.equal(body.previous.refundedCents, 0)
  assert.equal(body.previous.netCents, 4000)
  assert.equal(body.previous.paidOrders, 1)
  assert.equal(body.previous.averageOrderValueCents, 4000)
  assert.equal(new Date(body.previous.from) <= new Date('2024-01-10T12:00:00Z'), true)
  assert.equal(new Date(body.previous.to) < new Date('2024-02-01T00:00:00Z'), true)
  // Latest orders in the period, same currency scope as the rest of the dashboard (EUR order excluded).
  assert.equal(body.recentOrders.length, 3)
  const recent = body.recentOrders.find((row: { orderNumber: string }) => row.orderNumber === paid.order.orderNumber)
  assert.equal(recent.customerName, 'Test customer')
  assert.equal(recent.itemCount, 1)
  assert.equal(recent.totalCents, 5000)
  assert.equal(recent.status, 'DELIVERED')
  assert.equal(typeof recent.createdAt, 'string')
  const monthly = await request(path + '&groupBy=month', { token: adminToken })
  assert.equal(monthly.body.salesSeries.length, 1)
  assert.equal(monthly.body.salesSeries[0].revenueCents, 5000)
  const week = await request(path + '&groupBy=week', { token: adminToken })
  assert.equal(week.body.salesSeries[0].date, '2024-01-29')
  const empty = await request('/admin/dashboard?from=2020-01-01T00:00:00Z&to=2020-01-02T00:00:00Z', { token: adminToken })
  assert.equal(empty.body.revenue.netCents, 0)
  assert.equal(empty.body.orders.total, 0)
  assert.equal(empty.body.sales.unitsSold, 0)
  assert.equal(empty.body.bestsellers.length, 0)
  assert.equal(empty.body.salesSeries.length, 2)
  assert.equal(empty.body.salesSeries.every((row: { orders: number }) => row.orders === 0), true)
  await request('/admin/dashboard?from=2020-01-01T00:00:00Z&to=2026-01-01T00:00:00Z', { token: adminToken, status: 400 })
  await request('/admin/dashboard?from=2026-12-01T00:00:00Z&to=2026-11-01T00:00:00Z', { token: adminToken, status: 400 })
  await request('/admin/dashboard?currency=12', { token: adminToken, status: 400 })
  await request('/admin/dashboard?groupBy=year', { token: adminToken, status: 400 })
})
