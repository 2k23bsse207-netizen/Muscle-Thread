import assert from 'node:assert/strict'
import { test } from 'node:test'
import { adminId, adminToken, orderFixture, otherId, prisma, request, runId, userId, userToken } from './helpers.js'

test('Customers: admin-only search/list/detail/history, role exclusions and per-currency spend without secret fields', async () => {
  await request('/admin/customers', { status: 401 })
  await request('/admin/customers', { token: userToken, status: 403 })
  await prisma.user.update({ where: { id: userId }, data: { phone: '+1-555-0101' } })
  await orderFixture('customer-paid', userId, { status: 'PAID', totalCents: 5000, payment: 'PAID' })
  await orderFixture('customer-refunded', userId, { status: 'REFUNDED', totalCents: 2000, payment: 'REFUNDED' })
  await orderFixture('customer-eur', userId, { status: 'DELIVERED', totalCents: 7000, payment: 'PAID', currency: 'EUR' })
  await orderFixture('other-customer', otherId)
  const listed = await request(`/admin/customers?q=${runId}&limit=1&sortBy=email&sortOrder=asc`, { token: adminToken })
  assert.equal(listed.body.pagination.total, 2)
  assert.equal(listed.body.data.length, 1)
  assert.equal(listed.body.data[0].id === adminId, false)
  assert.equal(JSON.stringify(listed.body).includes('passwordHash'), false)
  const byPhone = await request('/admin/customers?q=555-0101', { token: adminToken })
  assert.equal(byPhone.body.pagination.total, 1)
  const detail = await request(`/admin/customers/${userId}`, { token: adminToken })
  assert.equal(detail.body.orderCount, 3)
  const spend = new Map<string, number>(detail.body.spending.map((row: { currency: string; totalSpentCents: number }) => [row.currency, row.totalSpentCents]))
  assert.equal(spend.get('USD'), 5000)
  assert.equal(spend.get('EUR'), 7000)
  assert.equal(JSON.stringify(detail.body).includes('passwordHash'), false)
  assert.equal(JSON.stringify(detail.body).includes('refreshTokenHash'), false)
  assert.equal(JSON.stringify(detail.body).includes('emailTokens'), false)
  const orders = await request(`/admin/customers/${userId}/orders?limit=1&status=PAID`, { token: adminToken })
  assert.equal(orders.body.pagination.total, 1)
  assert.equal(orders.body.data[0].userId, userId)
  await request(`/admin/customers/${userId}/orders?userId=${otherId}`, { token: adminToken, status: 400 })
  await request(`/admin/customers/${adminId}`, { token: adminToken, status: 404 })
  await request('/admin/customers/missing', { token: adminToken, status: 404 })
  await request('/admin/customers?emailVerified=not-boolean', { token: adminToken, status: 400 })
  await request('/admin/customers?sortBy=passwordHash', { token: adminToken, status: 400 })
  await request('/admin/customers?from=2026-12-01T00:00:00Z&to=2026-11-01T00:00:00Z', { token: adminToken, status: 400 })
})
